// Regenerates lib/watch2gether/emojiKeywords.en.ts and emojiKeywords.fr.ts.
//
// For every unicode emoji listed in lib/watch2gether/unicodeEmojis.ts, it pulls
// the EN and FR search keywords from the Unicode CLDR annotations and writes one
// accent-folded, space-joined keyword string per emoji per language. This is what
// lets the picker find 🍎 from "apple" (EN) / "pomme" (FR).
//
// Usage:  node scripts/gen-emoji-keywords.mjs
// Requires network access (fetches the CLDR JSON from GitHub).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const LIB = join(root, "lib", "watch2gether");

const CLDR =
  "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-annotations-full/annotations";

const fold = (s) =>
  s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");

function emojisFromUnicodeFile() {
  const ts = readFileSync(join(LIB, "unicodeEmojis.ts"), "utf8");
  const isEmoji = (s) =>
    [...s].some((c) => {
      const cp = c.codePointAt(0);
      return (
        (cp >= 0x1f000 && cp <= 0x1faff) ||
        (cp >= 0x2600 && cp <= 0x27bf) ||
        (cp >= 0x2190 && cp <= 0x21ff) ||
        (cp >= 0x2300 && cp <= 0x23ff) ||
        (cp >= 0x25a0 && cp <= 0x25ff) ||
        (cp >= 0x2b00 && cp <= 0x2bff) ||
        [0x203c, 0x2049, 0x2122, 0x00a9, 0x00ae].includes(cp)
      );
    });
  const seen = new Set();
  const out = [];
  for (const m of ts.matchAll(/"([^"]+)"/g)) {
    const e = m[1];
    if (isEmoji(e) && !seen.has(e)) {
      seen.add(e);
      out.push(e);
    }
  }
  return out;
}

function keywordsFor(emoji, table) {
  const a = table[emoji] || table[emoji.replace(/️/g, "")];
  const words = new Set();
  if (a) {
    for (const x of [...(a.default || []), ...(a.tts || [])]) {
      for (const p of fold(x).split(/\s+/)) if (p.length > 1) words.add(p);
    }
  }
  return words;
}

async function loadTable(lang) {
  const res = await fetch(`${CLDR}/${lang}/annotations.json`);
  if (!res.ok) throw new Error(`CLDR ${lang}: HTTP ${res.status}`);
  const json = await res.json();
  return json.annotations.annotations;
}

function writeMap(lang, varName, map) {
  const header = [
    "// GENERATED by scripts/gen-emoji-keywords.mjs — do not edit by hand.",
    `// ${lang} search keywords for the unicode emoji picker (Unicode CLDR ${lang}).`,
    "// Accent-stripped + lowercased. Emojis without a CLDR entry are omitted.",
    "",
    `export const ${varName}: Record<string, string> = {`,
  ];
  const body = Object.entries(map).map(
    ([e, v]) => `  ${JSON.stringify(e)}: ${JSON.stringify(v)},`,
  );
  const text = [...header, ...body, "};", ""].join("\n");
  writeFileSync(join(LIB, `emojiKeywords.${lang}.ts`), text);
  return body.length;
}

const ulist = emojisFromUnicodeFile();
const en = await loadTable("en");
const fr = await loadTable("fr");

const enMap = {};
const frMap = {};
for (const e of ulist) {
  const we = keywordsFor(e, en);
  const wf = keywordsFor(e, fr);
  if (we.size) enMap[e] = [...we].sort().join(" ");
  if (wf.size) frMap[e] = [...wf].sort().join(" ");
}

const nEn = writeMap("en", "EMOJI_KEYWORDS_EN", enMap);
const nFr = writeMap("fr", "EMOJI_KEYWORDS_FR", frMap);
console.log(`emojis: ${ulist.length} | en: ${nEn} | fr: ${nFr}`);
