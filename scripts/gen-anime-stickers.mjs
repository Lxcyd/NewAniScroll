// Regenerates lib/watch2gether/animeStickers.ts from the image files in
// public/emojis/anime/. Each file (png/gif) becomes one sticker whose shortcode
// is its filename, e.g. saitama.png → { shortcode: ":saitama:", ... }.
//
// It preserves any hand-curated `label`/`tags` already present in the existing
// animeStickers.ts (keyed by shortcode) so re-running doesn't clobber tweaks.
//
// Usage:  node scripts/gen-anime-stickers.mjs

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const DIR = join(root, "public", "emojis", "anime");
const OUT = join(root, "lib", "watch2gether", "animeStickers.ts");

// Pull existing { shortcode -> {label, tags} } so manual edits survive.
const existing = {};
try {
  const ts = readFileSync(OUT, "utf8");
  for (const m of ts.matchAll(
    /shortcode:\s*"(:[^"]+:)"[^}]*?label:\s*"([^"]*)"[^}]*?tags:\s*\[([^\]]*)\]/g,
  )) {
    const tags = [...m[3].matchAll(/"([^"]*)"/g)].map((t) => t[1]);
    existing[m[1]] = { label: m[2], tags };
  }
} catch {
  /* first run — no existing file */
}

const titleCase = (s) =>
  s.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()).trim();

const files = readdirSync(DIR)
  .filter((f) => /\.(png|gif)$/i.test(f))
  .sort();

const entries = files.map((file) => {
  const name = file.replace(/\.(png|gif)$/i, "");
  const shortcode = `:${name}:`;
  const prev = existing[shortcode];
  const label = prev?.label || titleCase(name);
  const tags = prev?.tags?.length ? prev.tags : name.split("_").filter(Boolean);
  const src = `/emojis/anime/${file}`;
  return `  { shortcode: ${JSON.stringify(shortcode)}, label: ${JSON.stringify(
    label,
  )}, src: ${JSON.stringify(src)}, tags: ${JSON.stringify(tags)} },`;
});

const text = `// GENERATED by scripts/gen-anime-stickers.mjs — do not edit by hand.
// One entry per image in public/emojis/anime/. Filename = shortcode.

export interface AnimeSticker {
  shortcode: string;
  label: string;
  src: string;
  tags?: string[];
}

export const ANIME_STICKERS: AnimeSticker[] = [
${entries.join("\n")}
];

export const ANIME_STICKER_MAP: Record<string, AnimeSticker> = Object.fromEntries(
  ANIME_STICKERS.map((s) => [s.shortcode, s]),
);

export function isAnimeSticker(shortcode: string): boolean {
  return shortcode in ANIME_STICKER_MAP;
}
`;

writeFileSync(OUT, text);
console.log(`wrote ${entries.length} stickers from ${files.length} files`);
